//! Resolvers for the sample decks used by qimu-core unit tests.
//!
//! Two decks are involved, with deliberately different dispositions:
//!
//! * **Redwood** (`Redwood_Visit_Revised_4tph_0_6vcr.pptx`) — a real
//!   17-slide deck used as a regression corpus. It is *not* committed:
//!   it is real-world content, and `*.pptx` is gitignored repo-wide.
//!   In CI it is therefore absent, and tests that need it print a
//!   [`SKIP_MARKER`] line and return early instead of panicking. On a
//!   machine that has the deck (the legacy `user/files/` location, or
//!   `QIMU_REDWOOD_DECK` pointing at the file) they run at full
//!   strength, exactly as before.
//! * **Case2** (`Case2_Charts_Animation.pptx`) — a synthetic 7-slide
//!   deck generated by `tools/make_case2.py`. CI regenerates it into
//!   `tests/fixtures/` before running the unit tests (see the
//!   p0-deckcraft workflow), so there the tests always execute, and
//!   the workflow fails the step if a Case2 skip marker still shows
//!   up in the log. Locally, generate it with
//!   `QIMU_CASE2_OUT=crates/qimu-core/tests/fixtures/Case2_Charts_Animation.pptx python3 tools/make_case2.py`
//!   (needs python-pptx, Pillow, and ffmpeg for the 7th, video, slide),
//!   or point `QIMU_CASE2_DECK` at an existing copy.

use std::path::PathBuf;

/// Prefix of the line a test emits (via `eprintln!`) when it skips
/// for a missing deck. Greppable on purpose: CI log checks match it.
pub const SKIP_MARKER: &str = "SKIP qimu-test-fixture";

/// The line a test prints before returning early for a missing deck.
pub fn skip_msg(what: &str) -> String {
    format!("{SKIP_MARKER}: {what} not available; test skipped")
}

fn try_read(candidates: &[PathBuf]) -> Option<Vec<u8>> {
    candidates.iter().find_map(|p| std::fs::read(p).ok())
}

/// Bytes of the Redwood deck, if it can be found on this machine.
pub fn redwood_deck() -> Option<Vec<u8>> {
    let mut candidates = Vec::new();
    if let Ok(p) = std::env::var("QIMU_REDWOOD_DECK") {
        candidates.push(PathBuf::from(p));
    }
    candidates.push(PathBuf::from(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../../user/files/Redwood_Visit_Revised_4tph_0_6vcr.pptx"
    )));
    candidates.push(PathBuf::from(
        "/home/hatch/workspace/user/files/Redwood_Visit_Revised_4tph_0_6vcr.pptx",
    ));
    try_read(&candidates)
}

/// Bytes of the Case2 deck, if it can be found on this machine.
pub fn case2_deck() -> Option<Vec<u8>> {
    let mut candidates = Vec::new();
    if let Ok(p) = std::env::var("QIMU_CASE2_DECK") {
        candidates.push(PathBuf::from(p));
    }
    candidates.push(PathBuf::from(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/tests/fixtures/Case2_Charts_Animation.pptx"
    )));
    candidates.push(PathBuf::from(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../../user/files/Case2_Charts_Animation.pptx"
    )));
    candidates.push(PathBuf::from(
        "/home/hatch/workspace/user/files/Case2_Charts_Animation.pptx",
    ));
    try_read(&candidates)
}
